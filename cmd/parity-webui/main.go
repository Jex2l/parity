// Command parity-webui serves the interactive HTML report viewer (spec
// 6.9: "minimal web report page... full cluster explorer, example
// browser with before/after side-by-side JSON diffs, perf charts, and
// noise-model inspector"). It's a single static binary: the frontend
// (HTML/CSS/JS, no build step, no CDN dependency) is embedded via
// go:embed, and the server just exposes the already-written report.json
// as JSON plus a list of sibling runs to switch between.
package main

import (
	"embed"
	"encoding/json"
	"flag"
	"fmt"
	"io/fs"
	"log"
	"net/http"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

//go:embed static
var staticFS embed.FS

func main() {
	reportPath := flag.String("report", "report.json", "path to a report.json written by `parity replay`")
	addr := flag.String("addr", ":4000", "address to listen on")
	flag.Parse()

	abs, err := filepath.Abs(*reportPath)
	if err != nil {
		log.Fatalf("parity-webui: %v", err)
	}
	dir := filepath.Dir(abs)

	sub, err := fs.Sub(staticFS, "static")
	if err != nil {
		log.Fatalf("parity-webui: %v", err)
	}
	mux := http.NewServeMux()
	mux.Handle("/", http.FileServer(http.FS(sub)))

	mux.HandleFunc("/api/report", func(w http.ResponseWriter, r *http.Request) {
		file := r.URL.Query().Get("file")
		path := abs
		if file != "" {
			// Only ever resolve within dir — never let a query param
			// escape to an arbitrary filesystem path.
			clean := filepath.Base(file)
			path = filepath.Join(dir, clean)
		}
		serveReportJSON(w, path)
	})

	mux.HandleFunc("/api/runs", func(w http.ResponseWriter, r *http.Request) {
		serveRunList(w, dir, abs)
	})

	mux.HandleFunc("/healthz", func(w http.ResponseWriter, r *http.Request) {
		w.WriteHeader(http.StatusOK)
	})

	log.Printf("parity-webui: serving %s on http://localhost%s", abs, *addr)
	if err := http.ListenAndServe(*addr, mux); err != nil {
		log.Fatalf("parity-webui: %v", err)
	}
}

// serveReportJSON always re-reads the file from disk — a report can be
// regenerated by a new `parity replay` run while the UI stays open, and
// re-reading means the browser's "refresh" button just works, with no
// server restart needed.
func serveReportJSON(w http.ResponseWriter, path string) {
	b, err := os.ReadFile(path)
	if err != nil {
		http.Error(w, fmt.Sprintf("reading report: %v", err), http.StatusNotFound)
		return
	}
	var v any
	if err := json.Unmarshal(b, &v); err != nil {
		http.Error(w, fmt.Sprintf("report is not valid JSON: %v", err), http.StatusInternalServerError)
		return
	}
	w.Header().Set("Content-Type", "application/json")
	w.Write(b)
}

type runInfo struct {
	File    string `json:"file"`
	Current bool   `json:"current"`
}

// serveRunList lists every *.json file in dir (sibling report files from
// previous runs), so the UI can offer a run switcher rather than only
// ever showing the one file the server was started with.
func serveRunList(w http.ResponseWriter, dir, currentAbs string) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		http.Error(w, err.Error(), http.StatusInternalServerError)
		return
	}
	var runs []runInfo
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".json") {
			continue
		}
		full := filepath.Join(dir, e.Name())
		runs = append(runs, runInfo{File: e.Name(), Current: full == currentAbs})
	}
	sort.Slice(runs, func(i, j int) bool { return runs[i].File < runs[j].File })

	w.Header().Set("Content-Type", "application/json")
	json.NewEncoder(w).Encode(runs)
}
